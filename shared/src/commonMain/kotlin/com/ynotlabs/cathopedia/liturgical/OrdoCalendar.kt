package com.ynotlabs.cathopedia.liturgical

import com.ynotlabs.cathopedia.resources.Res
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.datetime.DayOfWeek
import kotlinx.datetime.LocalDate
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/** Ranks of the Table of Liturgical Days, as graded by the Liturgical Calendar API (0–7). */
enum class OrdoRank {
    WEEKDAY,
    COMMEMORATION,
    OPTIONAL_MEMORIAL,
    MEMORIAL,
    FEAST,
    FEAST_OF_THE_LORD,
    SOLEMNITY,
    HIGHER_SOLEMNITY;

    companion object {
        fun ofGrade(grade: Int): OrdoRank = entries.getOrElse(grade) { WEEKDAY }
    }
}

/**
 * Which calendar the Ordo follows. The three differ in transfers (Epiphany, Ascension and Corpus
 * Christi on a weekday or the nearest Sunday) and, for [US], in national celebrations.
 */
enum class OrdoProfile(val file: String) {
    /** The General Roman Calendar as published: Epiphany 6 January, Ascension on Thursday. */
    GENERAL("calendar_general"),
    /** General Roman Calendar with Epiphany, Ascension and Corpus Christi kept on Sunday. */
    GENERAL_SUNDAY("calendar_general_sunday"),
    /** The proper calendar of the United States. */
    US("calendar_us"),
}

data class OrdoCelebration(
    val key: String,
    val name: String,
    val rank: OrdoRank,
    /** Lower-case LitCal colour names, e.g. "white", "purple"; the first is the usual one. */
    val colors: List<String>,
)

data class OrdoDay(
    val date: LocalDate,
    /** Highest rank first; on a weekday with optional memorials, the weekday comes first. */
    val celebrations: List<OrdoCelebration>,
    /** The weekday Mass whose readings are used on weekdays and memorials; null on Sundays and some feasts. */
    val ferialKey: String?,
    val sundayCycle: Char,
    val weekdayCycle: Int,
) {
    val principal: OrdoCelebration? get() = celebrations.firstOrNull()

    /** Optional memorials the celebrant may choose instead of the weekday. */
    val optionalMemorials: List<OrdoCelebration>
        get() = celebrations.filter { it.rank == OrdoRank.OPTIONAL_MEMORIAL }
}

enum class LectionaryKind {
    PROCESSION_GOSPEL,
    FIRST_READING,
    /** Commons only: the first reading from the New Testament used in Eastertide. */
    FIRST_READING_EASTER,
    PSALM,
    SECOND_READING,
    SEQUENCE,
    ACCLAMATION,
    GOSPEL,
}

data class LectionaryOption(val citation: String, val short: Boolean = false)

data class LectionaryReading(val kind: LectionaryKind, val options: List<LectionaryOption>)

data class MassReadingSet(
    /** The celebration the Mass is of. */
    val celebrationKey: String,
    val readings: List<LectionaryReading>,
    /** Commons (e.g. "Pastor", "Virgin") the celebrant may also choose readings from. */
    val commons: List<String> = emptyList(),
    /** True when the readings are the weekday's (a memorial or optional memorial being kept). */
    val weekdayReadings: Boolean = false,
)

/**
 * The offline Ordo: which Mass is celebrated on a day and its lectionary references.
 *
 * Data is generated by `tools/liturgy/build_ordo.py` (calendar from the Apache-2.0 Liturgical
 * Calendar API, references from the public-domain Tamil Catholic Lectionary list) and bundled
 * under files/content/ordo/. It covers [firstYear]..[lastYear]; outside that range [day] returns null.
 */
object OrdoCalendar {
    private const val DIR = "files/content/ordo"
    private val json = Json { ignoreUnknownKeys = true }
    private val mutex = Mutex()
    private val calendars = mutableMapOf<OrdoProfile, JsonObject>()
    private var lectionary: JsonObject? = null
    private var commons: JsonObject? = null
    private var names: Map<String, String> = emptyMap()

    const val firstYear = 2025
    const val lastYear = 2040

    suspend fun day(date: LocalDate, profile: OrdoProfile = OrdoProfile.GENERAL): OrdoDay? {
        if (date.year !in firstYear..lastYear) return null
        val years = calendar(profile)
        val key = date.month.ordinal.plus(1).toString().padStart(2, '0') + date.day.toString().padStart(2, '0')
        val raw = years[date.year.toString()]?.jsonObject?.get(key)?.jsonObject ?: return null
        val celebrations = raw["e"]!!.jsonArray.map { e ->
            val a = e.jsonArray
            val eventKey = a[0].jsonPrimitive.content
            OrdoCelebration(
                key = eventKey,
                name = names[eventKey] ?: eventKey,
                rank = OrdoRank.ofGrade(a[1].jsonPrimitive.int),
                colors = a[2].jsonPrimitive.content.split('/').filter(String::isNotBlank),
            )
        }.sortedByDescending {
            // An optional memorial is the celebrant's choice; by default the weekday Mass is said.
            if (it.rank <= OrdoRank.OPTIONAL_MEMORIAL && it.rank != OrdoRank.WEEKDAY) -1 else it.rank.ordinal
        }
        return OrdoDay(
            date = date,
            celebrations = celebrations,
            ferialKey = raw["f"]?.jsonPrimitive?.content,
            sundayCycle = LiturgicalCalendar.sundayCycleFor(date),
            weekdayCycle = LiturgicalCalendar.weekdayCycleFor(date),
        )
    }

    /**
     * The readings for [day]'s Mass, following the Lectionary's rules: Sundays, feasts and
     * solemnities have their own readings; on weekdays, memorials and optional memorials the
     * weekday readings are used, except where the memorial's readings are proper (e.g. the Gospel
     * of Our Lady of Sorrows), which then replace the weekday's.
     *
     * [celebrationKey] picks a different celebration of the day, e.g. an optional memorial.
     */
    suspend fun readings(day: OrdoDay, celebrationKey: String? = null): MassReadingSet? {
        loadLectionary()
        val chosen = day.celebrations.firstOrNull { it.key == celebrationKey } ?: day.principal ?: return null
        val isSunday = day.date.dayOfWeek == DayOfWeek.SUNDAY
        val ownReadings = chosen.rank >= OrdoRank.FEAST || isSunday || day.ferialKey == null
        val chosenEntry = lectionary?.get(chosen.key)?.jsonObject
        val chosenCommons = chosenEntry?.get("commons")?.jsonArray?.map { it.jsonPrimitive.content }.orEmpty()

        if (ownReadings) {
            val readings = readingsOf(chosen.key, day)
                ?: chosenCommons.firstOrNull()?.let(::commonReadings)
                ?: day.ferialKey?.let { readingsOf(it, day) }
                ?: return null
            return MassReadingSet(chosen.key, readings, chosenCommons)
        }

        val ferial = readingsOf(day.ferialKey!!, day) ?: return null
        // Applying proper readings only for celebrations actually kept today: obligatory memorials
        // always, an optional memorial only when the celebrant chose it.
        val kept = day.celebrations.filter {
            it.rank == OrdoRank.MEMORIAL || (it.key == chosen.key && it.rank == OrdoRank.OPTIONAL_MEMORIAL)
        }
        var readings = ferial
        for (celebration in kept) {
            val entry = lectionary?.get(celebration.key)?.jsonObject ?: continue
            val replaces = entry["replaces"]?.jsonArray?.map { LectionaryKind.valueOf(it.jsonPrimitive.content) }
                ?: continue
            val proper = readingsOf(celebration.key, day) ?: continue
            readings = readings.map { r ->
                if (r.kind in replaces) proper.firstOrNull { it.kind == r.kind } ?: r else r
            }
        }
        return MassReadingSet(chosen.key, readings, chosenCommons, weekdayReadings = true)
    }

    /** A celebration's own (proper or suggested) readings, e.g. to offer on a memorial instead of the weekday's. */
    suspend fun properReadings(day: OrdoDay, celebrationKey: String): List<LectionaryReading>? {
        loadLectionary()
        return readingsOf(celebrationKey, day)
    }

    /** The readings of a Common, e.g. "Pastor", "Martyr", "Mary". */
    suspend fun commonReadingsOf(common: String): List<LectionaryReading>? {
        loadLectionary()
        return commonReadings(common)
    }

    private fun readingsOf(key: String, day: OrdoDay): List<LectionaryReading>? {
        val cycles = lectionary?.get(key)?.jsonObject?.get("cycles")?.jsonObject ?: return null
        val pick = listOf(day.sundayCycle.toString(), if (day.weekdayCycle == 1) "I" else "II", "*")
            .firstNotNullOfOrNull { cycles[it] } ?: return null
        return parseReadings(pick.jsonArray).takeIf { it.isNotEmpty() }
    }

    private fun commonReadings(common: String): List<LectionaryReading>? =
        commons?.get(common)?.jsonArray?.let(::parseReadings)?.takeIf { it.isNotEmpty() }

    private fun parseReadings(array: JsonArray): List<LectionaryReading> = array.map { r ->
        val o = r.jsonObject
        LectionaryReading(
            kind = LectionaryKind.valueOf(o["kind"]!!.jsonPrimitive.content),
            options = o["options"]!!.jsonArray.map { opt ->
                val p = opt.jsonObject
                LectionaryOption(
                    citation = p["citation"]!!.jsonPrimitive.content,
                    short = p["short"]?.jsonPrimitive?.boolean ?: false,
                )
            },
        )
    }

    private suspend fun calendar(profile: OrdoProfile): JsonObject = mutex.withLock {
        if (names.isEmpty()) {
            names = json.decodeFromString(Res.readBytes("$DIR/names_en.json").decodeToString())
        }
        calendars.getOrPut(profile) {
            json.parseToJsonElement(Res.readBytes("$DIR/${profile.file}.json").decodeToString())
                .jsonObject["years"]!!.jsonObject
        }
    }

    private suspend fun loadLectionary() = mutex.withLock {
        if (lectionary == null) {
            val root = json.parseToJsonElement(Res.readBytes("$DIR/lectionary.json").decodeToString()).jsonObject
            lectionary = root["events"]!!.jsonObject
            commons = root["commons"]!!.jsonObject
        }
    }
}
